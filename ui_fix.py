def _ui_font(*args, **kwargs):
    """Global style-only font normalization: use a single sans-serif face.

    This keeps behaviour unchanged while converting the app's visual language
    from the previous terminal/techno look to a calmer, modern UI without
    touching interaction logic or widget state.
    """
    if not args:
        return _RawQFont(_UI_FONT_FAMILY, **kwargs)
    family = args[0]
    if isinstance(family, str):
        fam = family.strip().lower()
        if fam in {
            "courier new", "courier", "monospace", "consolas", "terminal",
            "times new roman", "georgia", "arial", "helvetica", "helvetica neue",
            "segoe ui emoji",
        }:
            args = (_UI_FONT_FAMILY,) + args[1:]
    return _RawQFont(*args, **kwargs)


