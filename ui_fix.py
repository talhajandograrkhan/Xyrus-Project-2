def _is_local_media_source(source: str) -> bool:
    """True only for real filesystem paths, never for remote media URLs.

    Passing a long Googlevideo URL into Path.exists() raises OSError: [Errno 63]
    File name too long. The UI must treat anything with a network scheme as a
    URL, even if the string contains ':' and '/' characters.
    """
    raw = (source or "").strip().strip('"').strip("'")
    if not raw:
        return False
    lowered = raw.lower()
    if lowered.startswith(("http://", "https://", "file://", "rtsp://",
                           "rtmp://", "mms://", "ftp://")):
        return False
    if "://" in raw:
        return False
    try:
        path = Path(raw).expanduser()
        return path.is_file()
    except OSError:
        return False
    except Exception:
        return False


